const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const script=fs.readFileSync('static/index.html','utf8').match(/<script>\s*([\s\S]*?)<\/script>/)[1];
new vm.Script(script);
const elements=new Map();
const $=id=>{if(!elements.has(id))elements.set(id,{hidden:true,value:0,removeAttribute(k){delete this[k];}});return elements.get(id);};
const ctx=vm.createContext({$});
vm.runInContext(script.slice(script.indexOf('function renderPathProgress(job) {'),script.indexOf('async function monitorPathImport')),ctx);
ctx.renderPathProgress({phase:'scanning'});
assert.equal($('path-progress-box').hidden,false);
assert.equal($('path-progress').value,undefined);
assert.match($('path-progress-text').textContent,/扫描/);
ctx.renderPathProgress({phase:'importing',status:'running',processed:7,total:20,count:6,skipped:1,filename:'test.jpg'});
assert.equal($('path-progress').value,35);
assert.match($('path-progress-text').textContent,/7 \/ 20/);
assert.match($('path-current').textContent,/test.jpg/);
ctx.renderPathProgress({phase:'complete',status:'complete',processed:20,total:20,count:19,skipped:1});
assert.equal($('path-progress').value,100);
console.log('PASS: scanning, real percentage, counts, current file and completion rendering');
